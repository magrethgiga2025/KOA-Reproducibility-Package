# -----------------------------------------------------------------------
# Geometry-adaptive niche fraction
# -----------------------------------------------------------------------

def _front_connectivity(F_nds, threshold_frac=0.15):
    """Estimate Pareto front connectivity as the fraction of non-dominated
    solutions that have at least one neighbour within threshold_frac of
    the normalised objective range.

    Returns a value in [0, 1]:
      1.0  -> fully connected (smooth, continuous front)
      ~0.0 -> highly disconnected (sparse, fragmented front)

    Used to set the niche_fraction parameter adaptively each generation.
    """
    if len(F_nds) < 3:
        return 1.0
    # normalise to [0,1] per objective
    lo = F_nds.min(axis=0); hi = F_nds.max(axis=0)
    rng_obj = np.where(hi - lo > 1e-10, hi - lo, 1.0)
    F_norm = (F_nds - lo) / rng_obj
    # pairwise distances in normalised space
    dists = np.sqrt(((F_norm[:, None] - F_norm[None, :]) ** 2).sum(axis=2))
    np.fill_diagonal(dists, np.inf)
    has_neighbour = (dists.min(axis=1) < threshold_frac).sum()
    return float(has_neighbour) / len(F_nds)


def _geometry_adaptive_truncate(F, n_survive, ref_dirs,
                                 norm: HyperplaneNormalization, rng,
                                 theta=0.15):
    """NSGA-III niche-balanced survival with a geometry-adaptive niche
    fraction. The fraction increases with measured front connectivity,
    so the algorithm automatically applies more uniform coverage pressure
    on smooth, connected fronts and reduces it on disconnected ones.
    """
    fronts = NonDominatedSorting().do(F, n_stop_if_ranked=n_survive)
    if len(fronts) == 0:
        return np.arange(min(n_survive, len(F)))

    until_last = (np.concatenate(fronts[:-1]).astype(int)
                  if len(fronts) > 1 else np.array([], dtype=int))
    last_front = np.asarray(fronts[-1], dtype=int)

    if len(until_last) >= n_survive:
        return until_last[:n_survive]

    n_remaining = n_survive - len(until_last)

    # geometry-adaptive niche fraction
    nds_idx = np.concatenate(fronts) if len(fronts) > 0 else np.arange(len(F))
    connectivity = _front_connectivity(F[nds_idx], threshold_frac=theta)
    # map connectivity to niche_fraction: 0.2 (disconnected) to 1.0 (connected)
    niche_fraction = float(np.clip(0.2 + 0.8 * connectivity, 0.2, 1.0))

    n_niche = int(round(n_remaining * niche_fraction))
    n_crowd = n_remaining - n_niche

    niche_of_ind, dist_to_niche, _ = associate_to_niches(
        F, ref_dirs, norm.ideal_point, norm.nadir_point
    )
    niche_count = (calc_niche_count(len(ref_dirs), niche_of_ind[until_last])
                   if len(until_last) > 0
                   else np.zeros(len(ref_dirs), dtype=int))

    chosen = set()

    if n_niche > 0:
        surv = niching(
            F[last_front], n_niche, niche_count,
            niche_of_ind[last_front], dist_to_niche[last_front],
            random_state=rng,
        )
        chosen.update(surv.tolist() if hasattr(surv, 'tolist') else list(surv))

    if n_crowd > 0:
        remaining = [i for i in range(len(last_front)) if i not in chosen]
        if remaining:
            cd = calc_crowding_distance(F[last_front[remaining]])
            order = np.argsort(-cd)
            for i in order[:n_crowd]:
                chosen.add(remaining[i])

    survivors_in_last = np.array(sorted(chosen), dtype=int)
    return np.concatenate([until_last, last_front[survivors_in_last]]).astype(int)


# -----------------------------------------------------------------------
# KOA-Star
# -----------------------------------------------------------------------

class KOAStar(Algorithm):
    """
    KOA* -- Kipunji Optimization Algorithm (final version).

    Two validated mechanisms:
      1. Adaptive state regulation with stagnation recovery.
      2. Archive-guided SHADE exploitation.

    Survival: geometry-adaptive niche-balanced selection
    (hyperplane normalisation from NSGA-III + connectivity-driven
    niche fraction).

    Parameters
    ----------
    pop_size : int
        Population size (default 100).
    n_archive : int
        External archive capacity (default 120).
    seed : int or None
        Random seed.
    """

    def __init__(self,
                 pop_size=100,
                 n_archive=120,
                 seed=None,
                 # state regulation
                 alpha0=0.3, A=0.15, tau=50,
                 # SHADE
                 shade_memory=10,
                 # diversity escape
                 eta_PI=20,
                 F_scale=0.5,
                 # stagnation
                 stagnation_patience=10,
                 stagnation_cooldown=15,
                 # geometry-adaptive survival
                 theta=0.15,
                 eps=1e-9,
                 **kwargs):
        super().__init__(**kwargs)
        self.pop_size = pop_size
        self.n_archive = n_archive
        self.seed = seed

        self.alpha0 = alpha0
        self.A = A
        self.tau = tau
        self.shade_memory = shade_memory
        self.eta_PI = eta_PI
        self.F_scale = F_scale
        self.stagnation_patience = stagnation_patience
        self.stagnation_cooldown = stagnation_cooldown
        self.theta = theta          # connectivity threshold for niche fraction
        self.eps = eps

        if seed is not None:
            self.rng = np.random.default_rng(seed)
        else:
            self.rng = np.random.default_rng()

        self._exploration_boost_gens = 0
        self._last_branch = None
        self.velocities = None

    # ------------------------------------------------------------------
    def _setup(self, problem, **kwargs):
        self.problem = problem
        n_obj = problem.n_obj
        self.koa_archive = ReferenceVectorArchive(self.n_archive, n_obj)
        self.shade = SuccessHistoryArchive(self.shade_memory)
        self.tracker = SearchStateTracker(
            stagnation_patience=self.stagnation_patience,
            cooldown=self.stagnation_cooldown,
        )
        self._norm = HyperplaneNormalization(n_obj)

        # reference directions for niche-balanced survival
        if n_obj == 2:
            self._surv_ref_dirs = get_reference_directions(
                "das-dennis", n_obj, n_partitions=self.pop_size - 1
            )
        else:
            n_part = 12 if n_obj == 3 else 6
            self._surv_ref_dirs = get_reference_directions(
                "das-dennis", n_obj, n_partitions=n_part
            )

    # ------------------------------------------------------------------
    def _initialize_infill(self):
        sampling = LHS()
        X = sampling.do(
            self.problem, self.pop_size, random_state=self.rng
        ).get("X")
        self.velocities = np.zeros_like(X)
        return Population.new(X=X)

    def _initialize_advance(self, infills=None, **kwargs):
        self.pop = infills
        F = self.pop.get("F")
        nds = NonDominatedSorting().do(F, only_non_dominated_front=True)
        self._norm.update(F, nds=nds)
        self.koa_archive.update(self.pop.get("X"), F)
        self.tracker.update(F, len(self.koa_archive.X) if self.koa_archive.X is not None else 0)

    # ------------------------------------------------------------------
    def _state_probabilities(self, t, T):
        """Adaptive exploration-exploitation balance.

        Uses two reference-front-free indicators:
          - convergence_rate: normalised ideal-point movement over the
            last `window` generations. Near 0 when the front has stalled.
          - diversity_ratio: current population diversity relative to its
            historical peak. Near 0 when the population has collapsed.

        The policy:
          - High convergence rate + high diversity -> increase exploitation
            (the population is diverse and converging; SHADE is working).
          - Low convergence rate + high diversity -> also increase exploitation
            (stall: SHADE needs more budget to find improving steps).
          - Low diversity -> increase exploration to recover spread.
          - Stagnation boost -> temporarily amplify exploration step size.
        """
        conv_rate = self.tracker.convergence_rate()
        div_ratio  = self.tracker.diversity_ratio()
        progress   = np.clip(t / max(T, 1), 0.0, 1.0)

        # base schedule: exploration decreases linearly with time
        p_explore  = 0.40 * (1.0 - progress) + 0.10 * progress
        # diversity collapse pulls weight toward exploration
        p_explore += (1.0 - div_ratio) * 0.20
        # convergence stall pulls weight toward exploitation
        p_explore -= (1.0 - conv_rate) * 0.15

        p_explore  = float(np.clip(p_explore, 0.05, 0.80))
        p_exploit  = 1.0 - p_explore
        return p_explore, p_exploit

    # ------------------------------------------------------------------
    def _infill(self):
        problem = self.problem
        N, D   = self.pop_size, problem.n_var
        xl, xu = problem.xl, problem.xu
        rng    = self.rng

        t = self.n_gen if self.n_gen is not None else 0
        T = (self.termination.n_max_gen
             if hasattr(self.termination, 'n_max_gen') else 300)

        # stagnation recovery
        was_stagnant = self.tracker.is_stagnant()
        if was_stagnant:
            self.tracker.trigger_recovery()
            self._exploration_boost_gens = 3
        boosting = self._exploration_boost_gens > 0
        if boosting:
            self._exploration_boost_gens -= 1

        p_explore, p_exploit = self._state_probabilities(t, T)

        X        = self.pop.get("X")
        F_pop    = self.pop.get("F")
        archive_X = (self.koa_archive.X
                     if self.koa_archive.X is not None else X)

        # adaptive exploration step amplitude
        alpha_t = self.alpha0 + self.A * np.sin(2.0 * np.pi * t / self.tau)
        if boosting:
            alpha_t *= 1.6

        s = rng.random(N)
        X_new = np.zeros_like(X)
        branch = np.zeros(N, dtype=int)     # 0 = explore, 1 = exploit

        for i in range(N):

            # --------------------------------------------------------
            # Mechanism 1b: exploration operator
            #   Archive-seeded random walk with Lévy perturbation.
            #   Draws the guide from the archive (not a fixed subgroup)
            #   so diversity pressure is spread across the whole
            #   front estimate rather than restricted to a local cluster.
            #   A Lévy step is added with probability 0.15 to enable
            #   occasional long-range jumps that can escape local optima.
            # --------------------------------------------------------
            if s[i] < p_explore:
                branch[i] = 0
                if len(archive_X) > 0:
                    x_guide = archive_X[rng.integers(0, len(archive_X))]
                else:
                    others = np.delete(np.arange(N), i)
                    x_guide = X[rng.choice(others)]

                diff = x_guide - X[i]
                norm = np.linalg.norm(diff) + self.eps
                # velocity update (exponential moving average)
                self.velocities[i] = (0.6 * self.velocities[i]
                                      + alpha_t * diff / norm)
                if rng.random() < 0.15:
                    self.velocities[i] += _levy_flight(D, 1.5, rng, size=1)[0]
                x_prime = np.clip(X[i] + self.velocities[i], xl, xu)

            # --------------------------------------------------------
            # Mechanism 2: archive-guided SHADE exploitation
            #   Adaptive differential evolution with success-history
            #   parameter control. The base vector is drawn from the
            #   reference-vector-clustered archive when available,
            #   providing geometry-aware guidance without requiring
            #   explicit reference-front knowledge.
            # --------------------------------------------------------
            else:
                branch[i] = 1
                F_de, CR_de = self.shade.sample_params(rng)
                if len(archive_X) > 0:
                    nb = self.koa_archive.neighborhood_sample(
                        i, min(3, len(archive_X)), rng
                    )
                    pool   = nb if nb is not None else archive_X
                    x_base = pool[rng.integers(0, len(pool))]
                else:
                    pool   = X
                    x_base = X[i]
                x_prime = _shade_de_trial(
                    X[i], x_base, pool, F_de, CR_de, xl, xu, rng
                )

            # defensive backstop
            if np.any(~np.isfinite(x_prime)):
                x_prime = X[i].copy()
            x_prime = np.clip(x_prime, xl, xu)
            x_prime = _polynomial_mutation(
                x_prime, prob=1.0 / D,
                eta=self.eta_PI, xl=xl, xu=xu, rng=rng
            )
            X_new[i] = x_prime

        self._last_branch = branch
        return Population.new(X=X_new)

    # ------------------------------------------------------------------
    def _advance(self, infills=None, **kwargs):
        P_old = self.pop
        P_new = infills

        X_union = np.vstack([P_old.get("X"), P_new.get("X")])
        F_union = np.vstack([P_old.get("F"), P_new.get("F")])

        # update normalisation before survival so this generation's
        # offspring inform the nadir estimate
        nds = NonDominatedSorting().do(F_union, only_non_dominated_front=True)
        self._norm.update(F_union, nds=nds)

        if self._norm.nadir_point is not None:
            # geometry-adaptive niche-balanced survival
            keep = _geometry_adaptive_truncate(
                F_union, self.pop_size,
                self._surv_ref_dirs, self._norm, self.rng,
                theta=self.theta
            )
        else:
            # fallback on first generation before norm is warm
            keep = _crowding_truncate(F_union, self.pop_size)

        self.pop = Population.new(X=X_union[keep], F=F_union[keep])

        # SHADE success-history update (mechanism 2)
        if self._last_branch is not None:
            exploit_idx = np.where(self._last_branch == 1)[0]
            old_F = P_old.get("F")
            new_F = P_new.get("F")
            for i in exploit_idx:
                if i < len(old_F) and i < len(new_F):
                    delta = float(np.sum(old_F[i]) - np.sum(new_F[i]))
                    if delta > 0:
                        F_de, CR_de = self.shade.sample_params(self.rng)
                        self.shade.record_success(F_de, CR_de, delta)
        self.shade.update_memory()

        # update archive and tracker
        self.koa_archive.update(P_new.get("X"), P_new.get("F"))
        n_arch = (len(self.koa_archive.X)
                  if self.koa_archive.X is not None else 0)
        self.tracker.update(self.pop.get("F"), n_arch)

    # ------------------------------------------------------------------
    def _set_optimum(self, **kwargs):
        if self.koa_archive.X is not None:
            self.opt = Population.new(
                X=self.koa_archive.X, F=self.koa_archive.F
            )
        else:
            self.opt = self.pop


# -----------------------------------------------------------------------
# Crowding-distance fallback (imported from v2, redefined here for safety)
# -----------------------------------------------------------------------
def _crowding_truncate(F, n_survive):
    fronts = NonDominatedSorting().do(F)
    survivors = []
    for front in fronts:
        if len(survivors) + len(front) <= n_survive:
            survivors.extend(front.tolist())
        else:
            needed = n_survive - len(survivors)
            cd = calc_crowding_distance(F[front])
            order = np.argsort(-cd)
            survivors.extend(front[order[:needed]].tolist())
            break
    return np.array(survivors, dtype=int)
